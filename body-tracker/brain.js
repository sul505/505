    out.push({ tone: gymDays >= 4 ? 'good' : gymDays >= 3 ? 'info' : 'warn', text: 'تمرنت ' + gymDays + ' أيام من هدف 4، ومشيت أو سويت كارديو ' + acts + ' مرات.' });
